"""Write docs/testing/extraction-accuracy.md from the summaries in evals/ocr/extraction.

    uv run python -m evals.extraction_report

Every number in the report is read from a `<engine>-<subset>.summary.json` written by
`evals.extract_bench`; nothing is typed by hand. With no summaries it says so.
"""

import argparse
import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path

type Summary = dict[str, object]

CAVEATS = """\
- **30 documents is a seed set.** A difference of a few points between engines is inside the
  noise, and the engine, the cutoff and the scores all use the same 30 documents.
- **One template per document type.** Real marksheets vary by board, print and language.
- **English only.** The synthetic pages carry no Devanagari.
- **A field counts as correct only when the app's extractor assigned the right value to the
  right field name** (names ignore case and word order, dates and roll numbers ignore case
  and spacing, marks compare as integers). Confidence and the review cutoff are not scored
  here: a correct value that the app would still send to review counts as correct.
- **A document that cannot be read counts as every field wrong** and stays in the 30.
- **The transfer certificate is counted in the headline** because the classifier and the
  matching rules support it; its accuracy is also listed on its own in the by-type table.
- **Tesseract runs on the same preprocessed pixels as RapidOCR**, with its tokens joined into
  phrases so the extractor sees the same kind of segments. Its page segmentation mode was
  chosen on the 10-document comparison set, which favours it, not the other engine.
"""

PERFECT_NOTE = (
    "An engine scored 1.0 on a clean page set. A perfect score on clean synthetic pages "
    "cannot separate engines, so the noisy subset is reported on its own."
)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m evals.extraction_report", description=__doc__)
    parser.add_argument("--results", type=Path, default=Path("evals/ocr/extraction"))
    parser.add_argument("--out", type=Path, default=Path("docs/testing/extraction-accuracy.md"))
    args = parser.parse_args(argv)

    summaries: list[Summary] = [
        json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(args.results.glob("*.summary.json"))
    ]
    if not summaries:
        sys.stdout.write("report: no summaries; run make eval-extract\n")
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(summaries), encoding="utf-8")
    sys.stdout.write(f"report: {len(summaries)} runs written to {args.out}\n")
    return 0


def render(summaries: Sequence[Mapping[str, object]]) -> str:
    if not summaries:
        return "# Extraction accuracy\n\nno summaries; run make eval-extract\n"
    ordered = sorted(summaries, key=lambda s: (str(s["subset"]), str(s["engine"])))
    lines = [
        "# Extraction accuracy on the synthetic set",
        "",
        "Generated by `python -m evals.extraction_report` from",
        "`evals/ocr/extraction/*.summary.json`.",
        "Each document goes through the app's own classifier and extractor, and every extracted",
        "field is compared with what the document prints (`data/seed/labels.json`).",
        "",
    ]
    if any(float(str(s["mean_field_accuracy"])) >= 1.0 for s in ordered):
        lines += [PERFECT_NOTE, ""]
    lines += _headline(ordered)
    lines += _comparison(ordered, "compare10", "Comparison on 10 documents")
    lines += _comparison(ordered, "noisy", "Noisiest 10 documents (blur, skew, shadow)")
    for summary in ordered:
        if summary["subset"] == "all":
            lines += _detail(summary)
    lines += ["## Caveats", "", CAVEATS]
    return "\n".join(lines)


def _headline(summaries: Sequence[Mapping[str, object]]) -> list[str]:
    return _comparison(summaries, "all", "All documents")


def _comparison(summaries: Sequence[Mapping[str, object]], subset: str, title: str) -> list[str]:
    rows = [s for s in summaries if s["subset"] == subset]
    if not rows:
        return []
    lines = [
        f"## {title}",
        "",
        "| Engine | Documents | Mean field accuracy | Type accuracy | Read errors |",
        "| --- | --- | --- | --- | --- |",
    ]
    for s in rows:
        lines.append(
            f"| {s['engine']} | {s['documents']} | {s['mean_field_accuracy']} "
            f"| {s['type_accuracy']} | {s['read_errors']} |"
        )
    return [*lines, ""]


def _detail(summary: Mapping[str, object]) -> list[str]:
    engine = summary["engine"]
    field_accuracy = _table(summary["field_accuracy"])
    by_type = _table(summary["by_doc_type"])
    lines = [f"## {engine}: accuracy by field", "", "| Field | Accuracy |", "| --- | --- |"]
    lines += [f"| {name} | {value} |" for name, value in field_accuracy.items()]
    lines += ["", f"## {engine}: accuracy by document type", ""]
    lines += ["| Document type | Field | Accuracy |", "| --- | --- | --- |"]
    for doc_type, fields in by_type.items():
        lines += [f"| {doc_type} | {name} | {value} |" for name, value in _table(fields).items()]
    failed = summary["failed_documents"]
    listed = ", ".join(str(d) for d in failed) if isinstance(failed, list) and failed else "none"
    lines += ["", f"Documents with at least one wrong field: {listed}.", ""]
    return lines


def _table(value: object) -> dict[str, object]:
    return dict(value) if isinstance(value, dict) else {}


if __name__ == "__main__":
    raise SystemExit(main())
