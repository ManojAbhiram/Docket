"""Write docs/research/ocr-benchmark.md from the summaries in evals/ocr/results.

    uv run python -m evals.report

Every number in the report is read from a `<variant>.summary.json` written by
`evals.ocr_bench`; nothing is typed by hand. With no summaries it says so.
"""

import argparse
import json
import sys
from pathlib import Path

FIELDS = ("name", "father_name", "dob", "roll_number", "board", "marks")
RAM_BUDGET_MB = 512

CAVEATS = """\
- **Scoring is presence in the OCR text.** A hit means the printed value appears in what
  the engine read; it does not prove a field extractor would assign it correctly. Names are
  order-free, dates tolerate `/`, `-` and `.`, marks must follow their subject. Treat the
  numbers as an upper bound on extraction.
- **CER** is the mean over printed values of the edit distance to the closest passage in the
  OCR text, divided by the value's length. Extra text on the page does not count against an
  engine. Case and whitespace are ignored.
- **30 documents is a seed set**, below the 50 cases the llm-eval skill asks for in an
  extraction eval. Differences of a few points between engines are inside the noise. The
  engine, the preprocessing and the reported scores all use the same 30 documents (Q-014).
- **One template per document type.** Real marksheets vary by board, print and language.
- **English only.** The synthetic pages carry no Devanagari, so the Hindi models are
  measured on Latin text and the Hindi question is still open.
- **Peak RSS** is the larger of the benchmark process and its children and includes the
  Python and library baseline. It is a laptop figure, not a Render instance figure.
- **Confidence** is each engine's own score and is not calibrated; the two means below show
  whether it separates documents read correctly from documents with a miss.
- The PP-OCRv6 detector with a v5 recogniser hybrid was **not run**: no verified way to
  configure it exists.
"""


def main() -> int:
    parser = argparse.ArgumentParser(prog="python -m evals.report", description=__doc__)
    parser.add_argument("--results", type=Path, default=Path("evals/ocr/results"))
    parser.add_argument("--out", type=Path, default=Path("docs/research/ocr-benchmark.md"))
    args = parser.parse_args()

    summaries = [
        json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(args.results.glob("*.summary.json"))
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(summaries), encoding="utf-8")
    sys.stdout.write(f"report: {len(summaries)} runs written to {args.out}\n")
    return 0 if summaries else 1


def render(summaries: list[dict[str, object]]) -> str:
    lines = [
        "# OCR benchmark on the synthetic set",
        "",
        "Generated by `python -m evals.report` from `evals/ocr/results/*.summary.json`.",
        "Method and dataset: see `docs/research/ocr-landscape.md` and `seed/`.",
        "",
    ]
    if not summaries:
        lines += [
            "**No benchmark results exist.** Run `bash scripts/run-ocr-benchmark.sh` first.",
            "",
        ]
        return "\n".join(lines)

    docs = summaries[0]["documents"]
    lines += [
        f"{len(summaries)} runs, {docs} documents each, every engine on the same images, with and "
        "without preprocessing (light flattening and deskew, `evals/preprocess.py`).",
        "",
        "## Results",
        "",
        "| Variant | Pre | Err | "
        + " | ".join(FIELDS)
        + " | CER | s/page p50 | s/page p95 | Prep s | Peak RAM MB | <= 512 |",
        "| --- | --- | --- | "
        + " | ".join("---" for _ in FIELDS)
        + " | --- | --- | --- | --- | --- | --- |",
    ]
    for item in summaries:
        accuracy = _dict(item["field_accuracy"])
        cells = [_pct(accuracy.get(field)) for field in FIELDS]
        ram = float(str(item["peak_rss_mb"]))
        lines.append(
            f"| {_setup(item)} "
            f"| {'yes' if item['preprocess'] else 'no'} | {item['errors']} | "
            + " | ".join(cells)
            + f" | {item['cer_mean']} | {item['seconds_per_page_p50']} "
            f"| {item['seconds_per_page_p95']} | {item['preprocess_seconds_mean']} "
            f"| {ram} | {'yes' if ram <= RAM_BUDGET_MB else 'no'} |"
        )

    lines += ["", "## Preprocessing effect", "", _preprocess_table(summaries), ""]
    lines += ["## Confidence", "", _confidence_table(summaries), ""]
    lines += ["## Reading the results", ""]
    lines += _reading(summaries)
    lines += ["", "## Limits of this benchmark", "", CAVEATS]
    return "\n".join(lines)


def _preprocess_table(summaries: list[dict[str, object]]) -> str:
    by_key: dict[str, dict[bool, dict[str, object]]] = {}
    for item in summaries:
        by_key.setdefault(_setup(item), {})[bool(item["preprocess"])] = item
    rows = [
        "| Setup | Mean field accuracy raw | with preprocessing | CER raw | with preprocessing |",
        "| --- | --- | --- | --- | --- |",
    ]
    for setup, pair in sorted(by_key.items()):
        if False not in pair or True not in pair:
            continue
        raw, pre = pair[False], pair[True]
        rows.append(
            f"| {setup} | {_pct(_mean_accuracy(raw))} "
            f"| {_pct(_mean_accuracy(pre))} | {raw['cer_mean']} | {pre['cer_mean']} |"
        )
    return "\n".join(rows)


def _confidence_table(summaries: list[dict[str, object]]) -> str:
    rows = [
        "| Variant | Pre | Mean confidence, documents fully read | with a miss |",
        "| --- | --- | --- | --- |",
    ]
    for item in summaries:
        rows.append(
            f"| {_setup(item)} "
            f"| {'yes' if item['preprocess'] else 'no'} "
            f"| {item.get('mean_confidence_docs_all_found')} "
            f"| {item.get('mean_confidence_docs_with_a_miss')} |"
        )
    return "\n".join(rows)


def _reading(summaries: list[dict[str, object]]) -> list[str]:
    fits = [s for s in summaries if float(str(s["peak_rss_mb"])) <= RAM_BUDGET_MB]
    lines = [
        f"- {len(fits)} of {len(summaries)} runs stayed at or under {RAM_BUDGET_MB} MB peak RSS "
        "on this machine."
    ]
    overall = max(summaries, key=lambda s: _mean_accuracy(s) or 0.0)
    lines.append(
        f"- Highest mean field accuracy overall: {_label(overall)} "
        f"({_pct(_mean_accuracy(overall))}, CER {overall['cer_mean']}, "
        f"{overall['peak_rss_mb']} MB peak). With 30 documents this is an indication, "
        "not a ranking."
    )
    if overall not in fits:
        over = float(str(overall["peak_rss_mb"])) - RAM_BUDGET_MB
        lines.append(
            f"- That run is {over:.1f} MB over the {RAM_BUDGET_MB} MB budget. A run that fits "
            "but reads far less is not a substitute: compare the accuracy columns before "
            "reading anything into the budget column."
        )
    if fits:
        best = max(fits, key=lambda s: _mean_accuracy(s) or 0.0)
        lines.append(
            f"- Highest mean field accuracy among the runs that fit: {_label(best)} "
            f"({_pct(_mean_accuracy(best))}, CER {best['cer_mean']}, {best['peak_rss_mb']} MB)."
        )
    failed = [s for s in summaries if int(str(s["errors"])) > 0]
    if failed:
        lines.append(
            "- Runs with engine errors (counted as every field missed): "
            + ", ".join(str(s["engine"]) for s in failed)
            + "."
        )
    return lines


def _setup(item: dict[str, object]) -> str:
    """The variant name without its preprocessing suffix: engine, language, size, images."""
    name = str(item.get("variant", item["engine"]))
    return name.replace("-preprocessed", "").replace("-raw", "")


def _label(item: dict[str, object]) -> str:
    return f"{_setup(item)}{' with preprocessing' if item['preprocess'] else ''}"


def _mean_accuracy(item: dict[str, object]) -> float | None:
    accuracy = _dict(item["field_accuracy"])
    values = [float(v) for v in accuracy.values()]
    return sum(values) / len(values) if values else None


def _dict(value: object) -> dict[str, float]:
    return {str(k): float(v) for k, v in value.items()} if isinstance(value, dict) else {}


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.0f}%"


if __name__ == "__main__":
    raise SystemExit(main())
